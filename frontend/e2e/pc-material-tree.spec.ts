import {test,expect} from '@playwright/test';
const base=process.env.PC_BASE_URL??'http://127.0.0.1:5193';
test('material categories collapse independently and preserve selected filtering',async({page})=>{
 await page.goto(base+'/admin/login');
 await page.getByLabel('账号',{exact:true}).fill('admin');await page.getByLabel('密码',{exact:true}).fill('123456');
 await page.getByRole('button',{name:/登.*录/}).click();await expect(page.locator('.topbar')).toBeVisible();
 await page.goto(base+'/admin/materials');
 const nav=page.getByRole('navigation',{name:'物料分类'});
 await expect(nav.getByRole('button',{name:'全部物料',exact:true})).toHaveCSS('color','rgb(40, 93, 89)');
 await expect(page.locator('.catalog-body .ant-table-thead th').first()).toHaveCSS('white-space','nowrap');
 await expect(nav.getByRole('button',{name:'工艺用水',exact:true})).toHaveCount(0);
 await expect(nav.getByRole('button',{name:'包装材料',exact:true})).toHaveCount(0);
 await nav.getByRole('button',{name:'展开包材',exact:true}).click();
 await expect(nav.getByRole('button',{name:'包装材料',exact:true})).toBeVisible();
 await nav.getByRole('button',{name:'收起包材',exact:true}).click();
 await expect(nav.getByRole('button',{name:'猪',exact:true})).toHaveCount(0);
 await nav.getByRole('button',{name:'展开原料',exact:true}).click();
 await expect(nav.getByRole('button',{name:'工艺用水',exact:true})).toBeVisible();
 await expect(nav.getByRole('button',{name:'猪',exact:true})).toBeVisible();
 await nav.getByRole('button',{name:'展开辅料',exact:true}).click();
 await expect(nav.getByRole('button',{name:'固体辅料',exact:true})).toBeVisible();
 const query=page.waitForRequest(r=>r.url().includes('/api/v1/materials?')&&new URL(r.url()).searchParams.get('classificationId')==='CAT-PORK');
 await nav.getByRole('button',{name:'猪',exact:true}).click();await query;
 await expect(nav.getByRole('button',{name:'猪',exact:true})).toHaveAttribute('aria-current','true');
 await nav.getByRole('button',{name:'收起原料',exact:true}).click();
 await expect(nav.getByRole('button',{name:'猪',exact:true})).toHaveCount(0);
 await expect(nav.getByRole('button',{name:'固体辅料',exact:true})).toBeVisible();
 await nav.getByRole('button',{name:'展开原料',exact:true}).click();
 await expect(nav.getByRole('button',{name:'猪',exact:true})).toHaveAttribute('aria-current','true');
 await nav.getByRole('button',{name:'全部物料',exact:true}).click();
 await expect(nav.getByRole('button',{name:'全部物料',exact:true})).toHaveAttribute('aria-current','true');
 await expect(page.getByRole('button',{name:'管理分类',exact:true})).toBeVisible();
 await expect(page.locator('.ant-spin-spinning')).toHaveCount(0);
 await page.screenshot({path:'test-results/material-tree.png',fullPage:true,animations:'disabled'});
});
test('engineer sees a clean collapsed catalog and can explicitly browse inactive history',async({page})=>{
 await page.route('**/api/v1/material-classifications',async route=>{
  const response=await route.fetch();const body=await response.json();
  body.data.push({id:'UI-INACTIVE-FIXTURE',parentId:null,name:'历史分类回归样例',businessType:'RAW',sortOrder:999,status:'INACTIVE',version:0});
  await route.fulfill({response,json:body});
 });
 await page.goto(base+'/admin/login');await page.getByLabel('账号',{exact:true}).fill('rnd_engineer');await page.getByLabel('密码',{exact:true}).fill('123456');
 await page.getByRole('button',{name:/登.*录/}).click();await expect(page.locator('.topbar')).toBeVisible();await page.goto(base+'/admin/materials');
 const nav=page.getByRole('navigation',{name:'物料分类'});
 await expect(nav.getByRole('button',{name:'原料',exact:true})).toBeVisible();
 await expect(nav.getByText('历史分类回归样例',{exact:true})).toHaveCount(0);
 await expect(page.getByRole('button',{name:'管理分类',exact:true})).toHaveCount(0);
 await expect(page.getByRole('button',{name:'新增物料',exact:true})).toHaveCount(0);
 await page.screenshot({path:'test-results/material-tree-clean.png',fullPage:true,animations:'disabled'});
 await nav.getByRole('checkbox',{name:'显示停用分类'}).check();
 await nav.getByRole('button',{name:'历史分类回归样例 停用',exact:true}).click();
 await nav.getByRole('checkbox',{name:'显示停用分类'}).uncheck();
 await expect(nav.getByText('历史分类回归样例',{exact:true})).toHaveCount(0);
 await expect(nav.getByRole('button',{name:'全部物料',exact:true})).toHaveAttribute('aria-current','true');
});
